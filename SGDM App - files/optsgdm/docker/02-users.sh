#!/bin/bash

set -e

mariadb -u root -p"${MARIADB_ROOT_PASSWORD}" <<-EOSQL
    DROP USER IF EXISTS '${DB_ADMIN_USER}'@'%';
    DROP USER IF EXISTS '${DB_APP_USER}'@'%';
    DROP USER IF EXISTS '${DB_CONSULTA_USER}'@'%';

    CREATE USER '${DB_ADMIN_USER}'@'%' IDENTIFIED BY '${DB_ADMIN_PASSWORD}';
    GRANT ALL PRIVILEGES ON ${MARIADB_DATABASE}.* TO '${DB_ADMIN_USER}'@'%';

    CREATE USER '${DB_APP_USER}'@'%' IDENTIFIED BY '${DB_APP_PASSWORD}';
    GRANT SELECT, INSERT, UPDATE, DELETE ON ${MARIADB_DATABASE}.* TO '${DB_APP_USER}'@'%';

    CREATE USER '${DB_CONSULTA_USER}'@'%' IDENTIFIED BY '${DB_CONSULTA_PASSWORD}';
    GRANT SELECT ON ${MARIADB_DATABASE}.torneo             TO '${DB_CONSULTA_USER}'@'%';
    GRANT SELECT ON ${MARIADB_DATABASE}.tipo_torneo        TO '${DB_CONSULTA_USER}'@'%';
    GRANT SELECT ON ${MARIADB_DATABASE}.modulo_competencia TO '${DB_CONSULTA_USER}'@'%';
    GRANT SELECT ON ${MARIADB_DATABASE}.torneo_modulo      TO '${DB_CONSULTA_USER}'@'%';
    GRANT SELECT ON ${MARIADB_DATABASE}.ronda              TO '${DB_CONSULTA_USER}'@'%';
    GRANT SELECT ON ${MARIADB_DATABASE}.inscripcion        TO '${DB_CONSULTA_USER}'@'%';
    GRANT SELECT ON ${MARIADB_DATABASE}.enfrentamiento     TO '${DB_CONSULTA_USER}'@'%';
    GRANT SELECT ON ${MARIADB_DATABASE}.resultado          TO '${DB_CONSULTA_USER}'@'%';
    GRANT SELECT ON ${MARIADB_DATABASE}.tabla_posiciones   TO '${DB_CONSULTA_USER}'@'%';
    GRANT SELECT ON ${MARIADB_DATABASE}.competidor         TO '${DB_CONSULTA_USER}'@'%';
    GRANT SELECT ON ${MARIADB_DATABASE}.participante       TO '${DB_CONSULTA_USER}'@'%';
    GRANT SELECT ON ${MARIADB_DATABASE}.equipo             TO '${DB_CONSULTA_USER}'@'%';
    GRANT SELECT ON ${MARIADB_DATABASE}.equipo_participante TO '${DB_CONSULTA_USER}'@'%';

    FLUSH PRIVILEGES;
EOSQL
